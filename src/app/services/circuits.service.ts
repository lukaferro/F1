  getCircuitById(id: string): Circuit | undefined {
    return this.circuits.find(c => c.id === id);
  }

  getCircuitsByCountry(countryCode: string): Circuit[] {
    return this.circuits.filter(c => c.country_code === countryCode);
  }

  getCircuitsByMacroRegion(region: string): Circuit[] {
    if (!region || region === 'world') return this.circuits;
    return this.circuits.filter(c => c.macro_region === region);
  }

  getSeasonCalendar(): Circuit[] {
    return [...this.circuits].sort((a, b) => (a.round_number || 0) - (b.round_number || 0));
  }
